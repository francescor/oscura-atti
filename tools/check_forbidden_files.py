#!/usr/bin/env python3
"""Refuse documents in the repository: they may contain personal data.

Checks file names (extensions) and file contents (PDF / CMS / ZIP / Office / image signatures),
so a renamed PDF is caught too. Used by the pre-commit hook (--staged) and by CI (all tracked files).
"""

import re
import subprocess
import sys

FORBIDDEN_EXT = (".pdf", ".p7m", ".p7s", ".zip", ".7z", ".doc", ".docx", ".odt", ".xls", ".xlsx", ".ods",
                 ".tif", ".tiff", ".jpg", ".jpeg", ".png", ".eml", ".msg")
MAGIC = [(b"%PDF-", "PDF"), (b"PK\x03\x04", "ZIP/Office"), (b"\xd0\xcf\x11\xe0", "legacy Office"),
         (b"\xff\xd8\xff", "JPEG"), (b"\x89PNG", "PNG"), (b"II*\x00", "TIFF"), (b"MM\x00*", "TIFF")]


def files(staged: bool) -> list[str]:
    cmd = ["git", "diff", "--cached", "--name-only", "--diff-filter=ACMR"] if staged else ["git", "ls-files"]
    return [f for f in subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.splitlines() if f]


def content(path: str, staged: bool) -> bytes:
    if staged:
        return subprocess.run(["git", "show", f":{path}"], capture_output=True, check=True).stdout[:4096]
    with open(path, "rb") as fh:
        return fh.read(4096)


def main() -> int:
    staged = "--staged" in sys.argv
    problems = []
    for f in files(staged):
        # README media generated by tools/make_media.py from an invented act: images/video only.
        if f.startswith("docs/media/") and f.lower().endswith((".png", ".gif", ".mp4")):
            head = content(f, staged)
            if b"%PDF-" not in head[:1024]:
                continue
        if f.lower().endswith(FORBIDDEN_EXT):
            problems.append(f"{f}: forbidden extension")
            continue
        try:
            head = content(f, staged)
        except (OSError, subprocess.CalledProcessError):
            continue
        for magic, kind in MAGIC:
            if head.startswith(magic):
                problems.append(f"{f}: looks like a {kind} file")
        # A PDF header with a version, at a line start within the first KB (junk before it is legal).
        if not head.startswith(b"%PDF-") and re.search(rb"(?m)^%PDF-\d\.\d", head[:1024]):
            problems.append(f"{f}: contains a PDF header")
        if head[:1] == b"\x30" and b"\x2a\x86\x48\x86\xf7\x0d\x01\x07\x02" in head[:64]:
            problems.append(f"{f}: looks like a signed CMS envelope (.p7m)")
    if problems:
        print("Documents must never be committed (they may contain personal data):", file=sys.stderr)
        for p in problems:
            print("  " + p, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
